/// Incompressible, de-duplication-proof payload with a CRC32C digest.
pub fn generate_payload(seed: u64, size: usize) -> (Bytes, u32) {
    let mut g = PayloadGen::new(seed, size);
    let mut buf = BytesMut::with_capacity(size);
    while let Some(piece) = g.next_piece(size.max(8)) {
        buf.extend_from_slice(&piece);
    }
    (buf.freeze(), g.crc())
}

/// The payload of [`generate_payload`], made a piece at a time: an object of any size is
/// written without ever being whole in memory (9.3.3 allocated each dataset object whole, and
/// `--object-size 64GiB` aborted the process before any budget applied). The bytes are the
/// same as [`generate_payload`]'s: the random stream is drawn in multiples of 8 bytes, which is
/// how the generator consumes it.
pub struct PayloadGen {
    rng: SmallRng,
    seed: u64,
    size: usize,
    pos: usize,
    crc: u32,
}

impl PayloadGen {
    pub fn new(seed: u64, size: usize) -> Self {
        Self {
            rng: SmallRng::seed_from_u64(seed ^ 0x9E37_79B9_7F4A_7C15),
            seed,
            size,
            pos: 0,
            crc: 0,
        }
    }

    /// The next piece, of at most `max` bytes (rounded down to a multiple of 8, at least 8);
    /// `None` at the end.
    pub fn next_piece(&mut self, max: usize) -> Option<Bytes> {
        if self.pos >= self.size {
            return None;
        }
        let len = (max / 8 * 8).max(8).min(self.size - self.pos);
        let mut buf = BytesMut::zeroed(len);
        self.rng.fill_bytes(&mut buf);
        // The seed at the start and its complement at the end (objects of 16 bytes or more).
        if self.size >= 16 {
            let (start, end) = (self.pos, self.pos + len);
            let head = self.seed.to_le_bytes();
            let tail = (!self.seed).to_le_bytes();
            for (i, b) in buf.iter_mut().enumerate() {
                let at = start + i;
                if at < 8 {
                    *b = head[at];
                } else if at >= self.size - 8 && at < end {
                    *b = tail[at - (self.size - 8)];
                }
            }
        }
        self.pos += len;
        self.crc = crate::util::crc32c_append(self.crc, &buf);
        Some(buf.freeze())
    }

    /// The CRC-32C of what was generated so far (the whole payload at the end).
    pub fn crc(&self) -> u32 {
        self.crc
    }
}

/// The piece a dataset object is generated and written in.
const PAYLOAD_PIECE: usize = 8 << 20;

/// Pre-generated random pool that write operations slice from (zero-copy), so that
/// measured writes don't spend client CPU generating data.
pub struct PayloadPool {
    buf: Bytes,
}

impl PayloadPool {
    /// A pool that [`PayloadPool::slice`] cuts payloads of up to `max_len` bytes from
    /// ([`super::ops::max_payload`] of the workload's operations).
    pub fn new(max_len: usize) -> Self {
        let len = max_len.max(64 * 1024) + 1024 * 1024;
        Self {
            buf: generate_payload(0xC0FFEE, len).0,
        }
    }

    /// `len` bytes of the pool, at a random offset. A pool smaller than `len` is an error,
    /// never a shorter payload: the operation would report a size it did not write.
    pub fn slice(&self, rng: &mut impl Rng, len: usize) -> Result<Bytes> {
        anyhow::ensure!(
            len <= self.buf.len(),
            "the payload pool holds {} B, less than the {len} B an operation writes",
            self.buf.len()
        );
        let max_off = self.buf.len() - len;
        let off = if max_off == 0 {
            0
        } else {
            rng.gen_range(0..max_off) & !7
        };
        Ok(self.buf.slice(off..off + len))
    }
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct DataObject {
    pub path: String,
    pub size: u64,
    /// CRC32C of the full object when generated by oprobe.
    pub crc: Option<u32>,
}

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Dataset {
    /// Prefix holding the objects (relative to the operator root).
    pub prefix: String,
    pub objects: Vec<DataObject>,
    /// `part=NN/` prefixes used by LIST operations.
    pub partitions: Vec<String>,
    /// True when objects already existed (user data or persisted dataset): never deleted.
    pub preexisting: bool,
    pub read_only: bool,
}

#[derive(Serialize, Deserialize)]
struct Manifest {
    objects: Vec<DataObject>,
    partitions: Vec<String>,
}

/// The name of a persisted dataset: what decides its objects and their sizes. A size
/// distribution is part of it (9.3.3 left it out, and a lognormal-size run reused a
/// fixed-size dataset); a dataset of fixed size keeps the name it had.
fn fingerprint(spec: &DatasetSpec, seed: u64) -> String {
    let mut s = format!(
        "{}|{}|{}|{seed}|v2",
        spec.objects,
        spec.object_size.0,
        spec.partitions.max(1)
    );
    if let Some(d) = &spec.size_dist {
        s.push_str(&format!("|{d}"));
    }
    format!("{:08x}", crate::util::crc32c(s.as_bytes()))
}

/// Best-effort removal of a failed/cancelled upload (bounded: the service may be unreachable,
/// which is often why the upload failed in the first place). `admin` is the cleanup operator:
/// outside the gate that stopped the upload.
async fn remove_partial(admin: &Operator, paths: Vec<String>, manifest: &str, persisted: bool) {
    let mut paths = paths;
    if persisted {
        paths.push(manifest.to_owned());
    }
    if paths.is_empty() {
        return;
    }
    let _ = tokio::time::timeout(std::time::Duration::from_secs(30), async {
        if admin.delete_iter(paths.clone()).await.is_err() {
            for p in paths {
                let _ = admin.delete(&p).await;
            }
        }
    })
    .await;
}

/// What the read of a persisted dataset's manifest says: `Some` a complete dataset to reuse,
/// `None` that there is none yet (the manifest does not exist, or does not parse: the dataset
/// is uploaded again). Any other failure, the run's gate refusing the read (a spent budget,
/// a cancellation) or the service failing, says nothing about the dataset, and stops the run
/// with the dataset left as it is: 9.3.2 took every failed read for an incomplete dataset,
/// uploaded it again over the shared objects, and when the same gate stopped that upload,
/// deleted them and the manifest with the ungated cleaner.
fn persisted_manifest(
    read: opendal::Result<opendal::Buffer>,
    path: &str,
    cancel: &crate::engine::Cancel,
) -> Result<Option<Manifest>> {
    match read {
        Ok(buf) => Ok(serde_json::from_slice::<Manifest>(&buf.to_vec()).ok()),
        Err(e) if e.kind() == opendal::ErrorKind::NotFound => Ok(None),
        Err(_) if cancel.is_cancelled() => bail!(CANCELLED),
        Err(e) => Err(anyhow::Error::new(e).context(format!(
            "cannot read the persisted dataset's manifest `{path}`; the dataset is left as it is"
        ))),
    }
}

/// What a dataset is prepared through.
#[derive(Clone, Copy)]
pub struct Via<'a> {
    /// Reads and uploads: behind the run's gate (budgets, cancellation).
    pub admin: &'a Operator,
    /// Removes a failed upload: outside the gate that stopped it.
    pub cleaner: &'a Operator,
    /// Where the multipart uploads that did not complete are aborted.
    pub aborts: &'a super::upload::Aborts,
}

/// The error of a dataset upload the run's cancellation stopped.
const CANCELLED: &str = "cancelled while uploading the dataset";

impl Dataset {
    /// Prepare the dataset: discover existing objects, reuse a persisted dataset, or upload one.
    ///
    /// A cancellation or a spent budget stops the upload's requests at the run's gate, and no
    /// further object starts once `cancel` fired. When the upload fails or is stopped, every
    /// multipart upload it left is aborted and every object it started is deleted again
    /// before the error is returned: no test data is left behind.
    pub async fn prepare(
        via: Via<'_>,
        spec: &DatasetSpec,
        seed: u64,
        run_prefix: &str,
        needs_objects: bool,
        cancel: &crate::engine::Cancel,
        progress: &(dyn Fn(String) + Send + Sync),
    ) -> Result<Self> {
        let Via {
            admin,
            cleaner,
            aborts,
        } = via;
        if let Some(prefix) = &spec.existing_prefix {
            return Self::discover(admin, prefix, spec.objects.max(1) * 64).await;
        }
        let partitions = spec.partitions.max(1);
        if !needs_objects {
            let base = format!("{run_prefix}data/");
            return Ok(Self {
                partitions: (0..partitions)
                    .map(|p| format!("{base}part={p:02}/"))
                    .collect(),
                prefix: base,
                ..Default::default()
            });
        }
        let (base, persisted) = if spec.persist {
            (format!("oprobe-dataset/{}/", fingerprint(spec, seed)), true)
        } else {
            (format!("{run_prefix}data/"), false)
        };
        let manifest_path = format!("{base}_manifest.json");
        let reusable = if persisted {
            persisted_manifest(admin.read(&manifest_path).await, &manifest_path, cancel)?
        } else {
            None
        };
        if let Some(m) = reusable {
            progress(format!(
                "reusing persisted dataset {base} ({} objects)",
                m.objects.len()
            ));
            return Ok(Self {
                prefix: base,
                objects: m.objects,
                partitions: m.partitions,
                preexisting: true,
                read_only: false,
            });
        }

        let size = spec.object_size.as_usize().max(1);
        let n = spec.objects.max(1);
        let t0 = Instant::now();
        let parts: Vec<String> = (0..partitions)
            .map(|p| format!("{base}part={p:02}/"))
            .collect();
        progress(format!(
            "uploading dataset: {n} × {} to {base}",
            crate::util::fmt_bytes(size as u64)
        ));
        let uploaded = std::sync::Mutex::new(Vec::<String>::new());
        let upload = futures::stream::iter(0..n)
            .map(|i| {
                let path = format!("{}obj-{i:05}.bin", parts[i % partitions]);
                let admin = admin.clone();
                let size = match &spec.size_dist {
                    Some(d) => d.size_of(seed, i) as usize,
                    None => size,
                };
                let uploaded = &uploaded;
                async move {
                    if cancel.is_cancelled() {
                        bail!(CANCELLED);
                    }
                    uploaded
                        .lock()
                        .unwrap_or_else(|e| e.into_inner())
                        .push(path.clone());
                    let failed = || format!("cannot upload dataset object `{path}`");
                    let w = admin
                        .writer_with(&path)
                        .chunk(8 * 1024 * 1024)
                        .concurrent(4)
                        .await
                        .with_context(failed)?;
                    let mut upload = super::upload::Upload::new(&admin, w, &path, aborts);
                    let mut g = PayloadGen::new(seed.wrapping_add(i as u64 * 7919), size);
                    loop {
                        let piece = tokio::task::spawn_blocking(move || {
                            let piece = g.next_piece(PAYLOAD_PIECE);
                            (g, piece)
                        })
                        .await
                        .context("payload generation task failed")?;
                        g = piece.0;
                        let Some(piece) = piece.1 else { break };
                        upload.write(piece).await.with_context(failed)?;
                    }
                    let crc = g.crc();
                    upload.close().await.with_context(failed)?;
                    Ok::<_, anyhow::Error>(DataObject {
                        path,
                        size: size as u64,
                        crc: Some(crc),
                    })
                }
            })
            .buffered(4)
            .try_collect::<Vec<DataObject>>();
        // The cancellation needs no `select!` here: the gate stops the requests of a cancelled
        // run, so each upload ends (and aborts) on its own, and no further one starts.
        let res = async {
            let objects = upload.await?;
            if persisted {
                let m = Manifest {
                    objects: objects.clone(),
                    partitions: parts.clone(),
                };
                admin.write(&manifest_path, serde_json::to_vec(&m)?).await?;
            }
            Ok::<_, anyhow::Error>(objects)
        }
        .await;
        let objects = match res {
            Ok(o) => o,
            Err(e) => {
                aborts.settle(cancel).await;
                let paths =
                    std::mem::take(&mut *uploaded.lock().unwrap_or_else(|e| e.into_inner()));
                progress(format!(
                    "dataset upload failed; removing {} partially uploaded objects",
                    paths.len()
                ));
                remove_partial(cleaner, paths, &manifest_path, persisted).await;
                let e = if cancel.is_cancelled() && e.downcast_ref::<OprobeError>().is_none() {
                    anyhow::anyhow!(CANCELLED)
                } else {
                    e
                };
                return Err(match aborts.failure() {
                    Some(unaborted) => e.context(unaborted),
                    None => e,
                });
            }
        };
        progress(format!(
            "dataset ready in {:.1}s",
            t0.elapsed().as_secs_f64()
        ));
        Ok(Self {
            prefix: base,
            objects,
            partitions: parts,
            preexisting: persisted,
            read_only: false,
        })
    }

    async fn discover(admin: &Operator, prefix: &str, limit: usize) -> Result<Self> {
        let prefix = if prefix.is_empty() || prefix.ends_with('/') {
            prefix.to_owned()
        } else {
            format!("{prefix}/")
        };
        let mut lister = admin
            .lister_with(&prefix)
            .recursive(true)
            .await
            .with_context(|| format!("cannot list existing data under `{prefix}`"))?;
        let mut objects = Vec::new();
        let mut parts = std::collections::BTreeSet::new();
        while let Some(e) = lister.try_next().await? {
            if e.metadata().mode() != EntryMode::FILE {
                continue;
            }
            let size = e.metadata().content_length();
            if size == 0 {
                continue;
            }
            if let Some((dir, _)) = e.path().rsplit_once('/') {
                parts.insert(format!("{dir}/"));
            }
            objects.push(DataObject {
                path: e.path().to_owned(),
                size,
                crc: None,
            });
            if objects.len() >= limit {
                break;
            }
        }
        if objects.is_empty() {
            return Err(crate::errors::OprobeError::new(
                crate::errors::ErrorCode::StorageNotFound,
                format!("no non-empty objects found under `{prefix}` (--existing / workload.dataset.existing_prefix)"),
            )
            .with_hint(
                "check the prefix is relative to the target's root and holds objects (e.g. list it with your storage CLI), or drop --existing to let oprobe upload a dataset",
            )
            .into());
        }
        let mut partitions: Vec<String> = parts.into_iter().take(64).collect();
        if partitions.is_empty() {
            partitions.push(prefix.clone());
        }
        Ok(Self {
            prefix,
            objects,
            partitions,
            preexisting: true,
            read_only: true,
        })
    }
}

/// Picks object indices according to the configured popularity distribution.
pub struct Picker {
    n: usize,
    access: Access,
    zipf_cdf: Vec<f64>,
}

impl Picker {
    pub fn new(n: usize, access: Access) -> Arc<Self> {
        let zipf_cdf = match access {
            Access::Zipf(s) if n > 0 => {
                let mut acc = 0.0;
                let mut cdf: Vec<f64> = (1..=n)
                    .map(|k| {
                        acc += 1.0 / (k as f64).powf(s);
                        acc
                    })
                    .collect();
                let total = acc;
                cdf.iter_mut().for_each(|v| *v /= total);
                cdf
            }
            _ => Vec::new(),
        };
        Arc::new(Self {
            n,
            access,
            zipf_cdf,
        })
    }

    pub fn pick<R: Rng + ?Sized>(&self, rng: &mut R) -> usize {
        if self.n <= 1 {
            return 0;
        }
        match self.access {
            Access::Uniform => rng.gen_range(0..self.n),
            Access::Zipf(_) => {
                let u: f64 = rng.r#gen();
                self.zipf_cdf.partition_point(|&c| c < u).min(self.n - 1)
            }
            Access::Hotset {
                fraction,
                probability,
            } => {
                let hot = ((self.n as f64 * fraction).ceil() as usize).clamp(1, self.n);
                if rng.gen_bool(probability.clamp(0.0, 1.0)) || hot == self.n {
                    rng.gen_range(0..hot)
                } else {
                    rng.gen_range(hot..self.n)
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// S5: an object is generated a piece at a time, and its bytes and CRC are the same as
    /// when it was generated whole (persisted datasets keep their checksums).
    #[test]
    fn a_payload_made_in_pieces_is_the_whole_payload() {
        for size in [0, 7, 15, 16, 17, 4096, 1_000_003] {
            let (whole, crc) = generate_payload(42, size);
            for piece in [8, 24, 4096, 1 << 20] {
                let mut g = PayloadGen::new(42, size);
                let mut joined = Vec::new();
                while let Some(p) = g.next_piece(piece) {
                    assert!(p.len() <= piece.max(8));
                    joined.extend_from_slice(&p);
                }
                assert_eq!(joined, whole.to_vec(), "size {size}, pieces of {piece}");
                assert_eq!(g.crc(), crc, "size {size}, pieces of {piece}");
            }
        }
    }

    #[test]
    fn payloads_are_unique_and_checksummed() {
        let (a, ca) = generate_payload(1, 4096);
        let (b, cb) = generate_payload(2, 4096);
        assert_ne!(a, b);
        assert_ne!(ca, cb);
        assert_eq!(crate::util::crc32c(&a), ca);
    }

    #[test]
    fn zipf_and_hotset_skew() {
        let mut rng = SmallRng::seed_from_u64(7);
        let z = Picker::new(100, Access::Zipf(1.2));
        let hits0 = (0..10_000).filter(|_| z.pick(&mut rng) == 0).count();
        assert!(hits0 > 1500, "zipf head too cold: {hits0}");
        let h = Picker::new(
            100,
            Access::Hotset {
                fraction: 0.1,
                probability: 0.9,
            },
        );
        let hot = (0..10_000).filter(|_| h.pick(&mut rng) < 10).count();
        assert!((8500..9500).contains(&hot), "{hot}");
        let u = Picker::new(10, Access::Uniform);
        assert!((0..1000).all(|_| u.pick(&mut rng) < 10));
    }

    fn spec() -> DatasetSpec {
        DatasetSpec {
            objects: 3,
            object_size: crate::util::ByteSize(1024),
            partitions: 1,
            persist: true,
            ..Default::default()
        }
    }

    async fn prepare(op: &Operator, cancel: &crate::engine::Cancel) -> Result<Dataset> {
        let aborts = super::super::upload::Aborts::new();
        let via = Via {
            admin: op,
            cleaner: op,
            aborts: &aborts,
        };
        Dataset::prepare(via, &spec(), 7, "oprobe-run-x/", true, cancel, &|_| {}).await
    }

    /// Only a manifest that does not exist sends a persisted dataset back to upload; a read
    /// the gate refused, or the service failed, stops the run without touching it.
    #[test]
    fn only_a_missing_manifest_is_an_incomplete_dataset() {
        let cancel = crate::engine::Cancel::default();
        let read = |kind, msg: &str| Err(opendal::Error::new(kind, msg.to_owned()));
        let missing = persisted_manifest(read(opendal::ErrorKind::NotFound, "no"), "m", &cancel);
        assert!(missing.unwrap().is_none());
        let garbled = persisted_manifest(Ok(opendal::Buffer::from("{")), "m", &cancel);
        assert!(garbled.unwrap().is_none());
        // The gate's refusals are `Unexpected`, persistent errors.
        let refused = read(opendal::ErrorKind::Unexpected, "request budget spent");
        let e = persisted_manifest(refused, "m", &cancel).err().unwrap();
        assert!(format!("{e:#}").contains("left as it is"), "{e:#}");
        cancel.cancel();
        let stopped = read(opendal::ErrorKind::Unexpected, "the run was cancelled");
        let e = persisted_manifest(stopped, "m", &cancel).err().unwrap();
        assert!(format!("{e:#}").contains("cancelled"), "{e:#}");
    }

    /// End to end on a filesystem: a persisted dataset whose manifest cannot be read (here
    /// it is a directory, an error that is not "not found") is neither uploaded again nor
    /// deleted.
    /// E3: a persisted dataset is named after its size distribution too.
    #[test]
    fn a_size_distribution_names_its_own_persisted_dataset() {
        let fixed = DatasetSpec {
            objects: 8,
            object_size: crate::util::ByteSize(64 * 1024),
            ..Default::default()
        };
        let dist = DatasetSpec {
            size_dist: Some("dist:lognormal(64KiB,1.5)".parse().unwrap()),
            ..fixed.clone()
        };
        assert_ne!(fingerprint(&fixed, 1), fingerprint(&dist, 1));
        // A fixed-size dataset keeps the name 9.3.3 gave it.
        let s = format!("8|{}|{}|1|v2", 64 * 1024, fixed.partitions.max(1));
        assert_eq!(
            fingerprint(&fixed, 1),
            format!("{:08x}", crate::util::crc32c(s.as_bytes()))
        );
    }

    #[tokio::test]
    async fn an_unreadable_manifest_leaves_the_persisted_dataset_alone() {
        let dir = tempfile::tempdir().unwrap();
        let op = Operator::new(opendal::services::Fs::default().root(dir.path().to_str().unwrap()))
            .unwrap();
        let cancel = crate::engine::Cancel::default();
        let first = prepare(&op, &cancel).await.unwrap();
        assert_eq!(first.objects.len(), 3);
        let manifest = format!("{}_manifest.json", first.prefix);
        let local = dir.path().join(&manifest);
        std::fs::remove_file(&local).unwrap();
        std::fs::create_dir(&local).unwrap();
        let e = prepare(&op, &cancel).await.unwrap_err();
        assert!(format!("{e:#}").contains("left as it is"), "{e:#}");
        for o in &first.objects {
            assert!(op.exists(&o.path).await.unwrap(), "{} was removed", o.path);
        }
        assert!(local.is_dir());
    }
}
