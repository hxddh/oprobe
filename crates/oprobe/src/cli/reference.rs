//! The CLI reference in Markdown, generated from the clap definition (`oprobe man --markdown`,
//! written to `docs/cli.md`; `tests/docs.rs` fails when the file drifts from the code).

use std::fmt::Write as _;

use clap::{Arg, Command, CommandFactory};

fn flag_names(a: &Arg) -> String {
    let mut names = Vec::new();
    if let Some(s) = a.get_short() {
        names.push(format!("-{s}"));
    }
    if let Some(l) = a.get_long() {
        names.push(format!("--{l}"));
    }
    let value = a
        .get_value_names()
        .map(|v| {
            v.iter()
                .map(|n| format!("<{n}>"))
                .collect::<Vec<_>>()
                .join(" ")
        })
        .filter(|_| a.get_action().takes_values());
    let mut s = if a.is_positional() {
        a.get_value_names()
            .and_then(|v| v.first().map(|n| format!("<{n}>")))
            .unwrap_or_else(|| format!("<{}>", a.get_id().as_str().to_ascii_uppercase()))
    } else {
        names.join(", ")
    };
    if !a.is_positional()
        && let Some(v) = value
    {
        s.push(' ');
        s.push_str(&v);
    }
    s
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn describe(a: &Arg) -> String {
    let mut d = a
        .get_long_help()
        .or_else(|| a.get_help())
        .map(|h| h.to_string())
        .unwrap_or_default();
    let pv: Vec<String> = a
        .get_possible_values()
        .iter()
        .filter(|p| !p.is_hide_set())
        .map(|p| format!("`{}`", p.get_name()))
        .collect();
    if !pv.is_empty() && a.get_action().takes_values() {
        let _ = write!(d, " · one of {}", pv.join(", "));
    }
    let defaults: Vec<String> = a
        .get_default_values()
        .iter()
        .map(|v| v.to_string_lossy().into_owned())
        .collect();
    if !defaults.is_empty() && a.get_action().takes_values() {
        let _ = write!(d, " · default `{}`", defaults.join(","));
    }
    if let Some(e) = a.get_env() {
        let _ = write!(d, " · env `{}`", e.to_string_lossy());
    }
    cell(d.trim())
}

fn args_table(out: &mut String, cmd: &Command, include_global: bool) {
    let args: Vec<&Arg> = cmd
        .get_arguments()
        .filter(|a| !a.is_hide_set())
        .filter(|a| a.get_id() != "help" && a.get_id() != "version")
        .filter(|a| include_global || !a.is_global_set())
        .collect();
    if args.is_empty() {
        return;
    }
    let mut headings: Vec<Option<&str>> = Vec::new();
    for a in &args {
        if !headings.contains(&a.get_help_heading()) {
            headings.push(a.get_help_heading());
        }
    }
    for h in headings {
        if let Some(h) = h {
            let _ = writeln!(out, "\n*{h}*\n");
        } else {
            out.push('\n');
        }
        out.push_str("| argument | description |\n|---|---|\n");
        for a in args.iter().filter(|a| a.get_help_heading() == h) {
            let _ = writeln!(out, "| `{}` | {} |", cell(&flag_names(a)), describe(a));
        }
    }
}

fn command(out: &mut String, cmd: &Command, path: &str) {
    if cmd.is_hide_set() || cmd.get_name() == "help" {
        return;
    }
    let _ = writeln!(out, "\n## `{path}`\n");
    if let Some(about) = cmd.get_long_about().or_else(|| cmd.get_about()) {
        let _ = writeln!(out, "{about}\n");
    }
    let aliases: Vec<&str> = cmd.get_visible_aliases().collect();
    if !aliases.is_empty() {
        let _ = writeln!(out, "Aliases: {}\n", aliases.join(", "));
    }
    let mut c = cmd.clone();
    let usage = c.render_usage().to_string();
    let usage = usage.trim_start_matches("Usage: ").trim();
    let _ = writeln!(out, "```text\n{usage}\n```");
    if !cmd.has_subcommands() {
        let rel = path.strip_prefix("oprobe ").unwrap_or(path);
        let f = super::formats::names(super::formats::formats_of(rel));
        let _ = writeln!(out, "\nOutput formats (`-o`): {}", f.join(", "));
    }
    args_table(out, cmd, false);
    for sub in cmd.get_subcommands() {
        command(out, sub, &format!("{path} {}", sub.get_name()));
    }
}

/// The whole reference.
pub fn markdown() -> String {
    let mut root = super::Cli::command();
    root.build();
    let mut out = String::from(
        "# CLI reference\n\n<!-- Generated by `oprobe man --markdown` from the command definitions; \
         do not edit by hand. Refresh: `OPROBE_BLESS=1 cargo test --test docs`. -->\n\n",
    );
    if let Some(a) = root.get_long_about() {
        let _ = writeln!(out, "{a}\n");
    }
    out.push_str("Every command accepts the global options below. Exit codes: `0` ok · `1` runtime failure · `2` usage/config · `3` SLA failed or regression · `4` budget exceeded · `5` safety refusal · `130` interrupted.\n\n## Global options\n");
    args_table(&mut out, &root, true);
    out.push_str("\n## Commands\n\n| command | what it does |\n|---|---|\n");
    for sub in root.get_subcommands() {
        if sub.is_hide_set() || sub.get_name() == "help" {
            continue;
        }
        let _ = writeln!(
            out,
            "| [`oprobe {}`](#oprobe-{}) | {} |",
            sub.get_name(),
            sub.get_name(),
            cell(&sub.get_about().map(|a| a.to_string()).unwrap_or_default())
        );
    }
    for sub in root.get_subcommands() {
        command(&mut out, sub, &format!("oprobe {}", sub.get_name()));
    }
    out
}
