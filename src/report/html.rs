    #[test]
    fn large_runs_are_sampled_keeping_errors_and_slow_requests() {
        let mut run = super::super::fixture::run();
        let template = run.reqs[0].clone();
        run.reqs = (0..20_000u64)
            .map(|i| {
                let mut r = template.clone();
                r.t_us = i as i64 * 10;
                r.op_id = 1000 + i;
                r.total_us = if i == 17_777 { 9_999_999 } else { 1000 + i % 7 };
                r.status = if i % 5000 == 1 { 503 } else { 200 };
                r
            })
            .collect();
        let (rows, sampled) = select_rows(&run);
        assert!(sampled);
        assert!(rows.len() <= MAX_ROWS);
        assert!(rows.iter().any(|r| r.total_us == 9_999_999));
        assert_eq!(rows.iter().filter(|r| r.status == 503).count(), 4);
        assert!(rows.windows(2).all(|w| w[0].t_us <= w[1].t_us));
    }

