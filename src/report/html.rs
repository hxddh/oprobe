//! The single-file HTML report (`-o html` on `run`, `runs show`, `compare`; `runs export
//! --format html`).
//!
//! One self-contained document: inline CSS and a small hand-written script, charts drawn here
//! as inline SVG with real axes and units (log latency axes, stepped lines, no smoothing,
//! native hover readouts through `<title>`), the request rows embedded as JSON for the
//! filterable/sortable table. Nothing is fetched from the network; the page works offline,
//! follows the light/dark preference (with a toggle) and prints cleanly.

