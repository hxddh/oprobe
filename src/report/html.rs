/// The regression gate (`oprobe compare -o html`) as a self-contained page.
pub fn render_compare(d: &DiffReport) -> String {
    let mut b = String::new();
    let (cls, icon, label) = if d.passed {
        ("st-ok", "✓", "PASSED")
    } else {
        ("st-critical", "✖", "FAILED")
    };
    let _ = write!(
        b,
        "<header class=\"top\"><div><div class=\"brand\">oprobe compare</div><h1>Regression gate</h1>\
         <div class=\"meta\">baseline <code>{}</code> · candidate <code>{}</code></div></div>\
         <button id=\"theme\" class=\"noprint\" type=\"button\" aria-label=\"Switch light or dark theme\">◐ Theme</button></header>",
        esc(&d.baseline),
        esc(&d.candidate)
    );
    let fails = d.checks.iter().filter(|c| c.status == Status::Fail).count();
    let _ = write!(
        b,
        "<section id=\"verdict\"><div class=\"verdict\"><span class=\"pill {cls}\">{icon} {label}</span><p class=\"headline\">{}</p></div>",
        if d.passed {
            "No check exceeded its limit.".to_owned()
        } else {
            format!("{fails} check(s) exceeded their limit (exit code 3).")
        }
    );
    for w in &d.warnings {
        let _ = write!(
            b,
            "<p><span class=\"pill st-attention\">▲ warning</span> {}</p>",
            esc(w)
        );
    }
    b += "</section>";
    if !d.config_changes.is_empty() {
        b += "<section><h2>Configuration changes</h2><div class=\"tablewrap\"><table><thead><tr><th>kind</th><th class=\"l\">setting</th><th class=\"l\">baseline</th><th class=\"l\">candidate</th></tr></thead><tbody>";
        for c in &d.config_changes {
            let _ = write!(
                b,
                "<tr><td>{}</td><td class=\"l\"><code>{}</code></td><td class=\"l\">{}</td><td class=\"l\">{}</td></tr>",
                c.kind.label(),
                esc(&c.field),
                esc(&c.baseline),
                esc(&c.candidate)
            );
        }
        b += "</tbody></table></div></section>";
    }
    b += "<section><h2>Checks</h2><div class=\"tablewrap\"><table><thead><tr><th>check</th><th>baseline</th><th>candidate</th><th>change</th><th class=\"l\">limit</th><th class=\"l\">result</th></tr></thead><tbody>";
    for c in &d.checks {
        let (cls, txt) = match c.status {
            Status::Pass => ("st-ok", "✓ pass"),
            Status::Improved => ("st-review", "▲ improved"),
            Status::Fail => ("st-critical", "✖ fail"),
            Status::Skipped => ("", "– skipped"),
        };
        let _ = write!(
            b,
            "<tr><td>{}</td><td>{}</td><td>{}</td><td>{:+.1}%</td><td class=\"l\">{}</td><td class=\"l\"><span class=\"pill {cls}\">{txt}</span>{}</td></tr>",
            esc(&c.name),
            fmt_num(c.baseline),
            fmt_num(c.candidate),
            c.change_pct,
            esc(&c.limit),
            if c.note.is_empty() {
                String::new()
            } else {
                format!(" <span class=\"muted\">{}</span>", esc(&c.note))
            }
        );
    }
    b += "</tbody></table></div></section>";
    page(
        &format!("oprobe compare · {} → {}", d.baseline, d.candidate),
        &b,
        None,
    )
}

