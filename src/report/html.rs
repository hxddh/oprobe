/// Escape text for HTML content and attribute values.
pub fn esc(s: &str) -> String {
    let mut o = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => o.push_str("&amp;"),
            '<' => o.push_str("&lt;"),
            '>' => o.push_str("&gt;"),
            '"' => o.push_str("&quot;"),
            '\'' => o.push_str("&#39;"),
            c => o.push(c),
        }
    }
    o
}

/// JSON safe inside a `<script>` element (no `<` can end it).
fn script_json(v: &serde_json::Value) -> String {
    serde_json::to_string(v)
        .unwrap_or_else(|_| "null".into())
        .replace('<', "\\u003c")
}

/// The full HTML report of a run (with its trace rows).
pub fn render(run: &Run) -> String {
    let r = &run.report;
    let mut b = String::new();
    b += &header(r);
    b += &toc(run);
    b += &verdict_section(r);
    b += &findings_section(r, run);
    b += &time_section(r);
    b += &timeline_section(r);
    b += &heatmap_section(r);
    b += &operations_section(r);
    b += &waterfall_section(run);
    let rows = requests_section(run);
    b += &rows.0;
    b += &network_section(r);
    b += &cost_section(r);
    b += &environment_section(r);
    let title = format!("oprobe · {} · {}", r.target.display, r.run.id);
    page(&title, &b, rows.1.as_deref())
}

/// The HTML report of a report without trace rows (e.g. a report `.json`).
pub fn render_report(r: &Report) -> String {
    render(&Run {
        report: r.clone(),
        ops: Vec::new(),
        reqs: Vec::new(),
    })
}

fn page(title: &str, body: &str, rows_json: Option<&str>) -> String {
    let mut o = String::with_capacity(body.len() + CSS.len() + JS.len() + 512);
    o += "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n";
    o += "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n";
    o += "<meta name=\"generator\" content=\"oprobe\">\n";
    let _ = writeln!(o, "<title>{}</title>", esc(title));
    o += "<style>";
    o += CSS;
    o += "</style>\n</head>\n<body>\n<div class=\"wrap\">\n";
    o += body;
    let _ = writeln!(
        o,
        "<footer>Generated by oprobe {} · a single self-contained file: nothing is loaded from \
         the network.</footer>",
        esc(env!("CARGO_PKG_VERSION"))
    );
    o += "</div>\n";
    if let Some(j) = rows_json {
        o += "<script type=\"application/json\" id=\"oprobe-rows\">";
        o += j;
        o += "</script>\n";
    }
    o += "<script>";
    o += JS;
    o += "</script>\n</body>\n</html>\n";
    o
}

