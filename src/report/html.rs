fn time_section(r: &Report) -> String {
    let parts = r.stages.shares.parts();
    let mut o = String::from(
        "<section id=\"time\"><h2>Where the time goes</h2><p class=\"sub\">Share of total \
         operation wall time per layer.</p>",
    );
    // A 100% stacked bar with 2px gaps between segments.
    let (w, h) = (720.0, 34.0);
    let total: f64 = parts.iter().map(|p| p.1.max(0.0)).sum::<f64>().max(1e-9);
    let mut svg = format!(
        "<svg class=\"viz\" viewBox=\"0 0 {w} {h}\" role=\"img\" aria-label=\"Share of operation time per layer\">"
    );
    let mut x = 0.0;
    for (i, (name, pct)) in parts.iter().enumerate() {
        let frac = pct.max(0.0) / total;
        let sw = frac * w;
        if sw >= 0.5 {
            let gap = if x + sw < w - 0.5 { 2.0 } else { 0.0 };
            let _ = write!(
                svg,
                "<rect class=\"seg\" x=\"{x:.1}\" y=\"4\" width=\"{:.1}\" height=\"{}\" rx=\"3\" fill=\"{}\"><title>{name}: {pct:.1}%</title></rect>",
                (sw - gap).max(0.5),
                h - 8.0,
                STAGES[i].1
            );
        }
        x += sw;
    }
    svg += "</svg>";
    o += &svg;
    o += "<div class=\"tablewrap\"><table><thead><tr><th>layer</th><th>share</th><th class=\"l\">what it is</th></tr></thead><tbody>";
    for (i, (name, pct)) in parts.iter().enumerate() {
        let _ = write!(
            o,
            "<tr><td><span class=\"swatch\" style=\"background:{}\"></span>{name}</td><td>{pct:.1}%</td><td class=\"l\">{}</td></tr>",
            STAGES[i].1, STAGES[i].2
        );
    }
    o += "</tbody></table></div>";

    let rp = &r.stages.request_p99;
    o += "<div class=\"grid2\"><div><h3>Request stages (p99 across requests)</h3><dl class=\"kv\">";
    for (k, v) in [
        ("queue", rp.queue_ms),
        ("connect (dialing requests)", rp.connect_ms),
        ("send", rp.send_ms),
        ("time to first byte", rp.ttfb_ms),
        ("body transfer", rp.body_ms),
        ("consumer stall", rp.stall_ms),
        ("total", rp.total_ms),
    ] {
        let _ = write!(o, "<dt>{k}</dt><dd>{}</dd>", fmt_ms(v));
    }
    o += "</dl></div>";
    if !r.stages.per_verb.is_empty() {
        o += "<div><h3>Mean breakdown per operation</h3><div class=\"tablewrap\"><table><thead><tr><th>operation</th><th>queue</th><th>cache</th><th>backend</th><th>retry</th><th>client</th></tr></thead><tbody>";
        for v in &r.stages.per_verb {
            let b = &v.breakdown;
            let _ = write!(
                o,
                "<tr><td><code>{}</code></td><td>{}</td><td>{}</td><td>{}</td><td>{}</td><td>{}</td></tr>",
                esc(&v.verb),
                fmt_ms(b.queue_ms),
                fmt_ms(b.cache_ms),
                fmt_ms(b.backend_ms),
                fmt_ms(b.retry_ms),
                fmt_ms(b.client_ms)
            );
        }
        o += "</tbody></table></div></div>";
    }
    o += "</div></section>\n";
    o
}

