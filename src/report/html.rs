const CW: f64 = 720.0;
const CH: f64 = 190.0;
const ML: f64 = 58.0;
const MR: f64 = 14.0;
const MT: f64 = 10.0;
const MB: f64 = 32.0;

/// "Nice" linear ticks covering `0..=max`.
fn lin_ticks(max: f64) -> (f64, Vec<f64>) {
    let max = if max.is_finite() && max > 0.0 {
        max
    } else {
        1.0
    };
    let raw = max / 4.0;
    let mag = 10f64.powf(raw.log10().floor());
    let step = [1.0, 2.0, 2.5, 5.0, 10.0]
        .iter()
        .map(|m| m * mag)
        .find(|s| *s >= raw)
        .unwrap_or(10.0 * mag);
    let top = (max / step).ceil() * step;
    let n = (top / step).round() as usize;
    (top, (0..=n).map(|i| i as f64 * step).collect())
}

/// Decade-aligned log ticks covering `lo..=hi` (both > 0); adds 2× and 5× when the range
/// spans fewer than three decades.
fn log_ticks(lo: f64, hi: f64) -> (f64, f64, Vec<f64>) {
    let lo = if lo > 0.0 { lo } else { 0.01 };
    let hi = hi.max(lo * 1.0001);
    let mut a = 10f64.powf(lo.log10().floor());
    let mut b = 10f64.powf(hi.log10().ceil());
    if b <= a {
        b = a * 10.0;
    }
    let decades = (b / a).log10().round() as i32;
    let mut ticks = Vec::new();
    let mut d = a;
    for _ in 0..=decades {
        ticks.push(d);
        if decades < 3 {
            for m in [2.0, 5.0] {
                if d * m < b {
                    ticks.push(d * m);
                }
            }
        }
        d *= 10.0;
    }
    ticks.sort_by(|x, y| x.total_cmp(y));
    // Trim empty decades at the ends only when the data leaves room.
    if a < lo / 10.0 {
        a = 10f64.powf(lo.log10().floor());
    }
    (a, b, ticks)
}

fn tick_label(v: f64, unit: &str) -> String {
    let n = if v == 0.0 {
        "0".to_owned()
    } else if v.abs() >= 1000.0 && unit == "ms" {
        return format!("{}s", trim_num(v / 1000.0));
    } else {
        trim_num(v)
    };
    format!("{n}{unit}")
}

fn trim_num(v: f64) -> String {
    if v.abs() >= 1_000_000.0 {
        format!("{}M", trim_num(v / 1_000_000.0))
    } else if v.abs() >= 10_000.0 {
        format!("{}k", trim_num(v / 1000.0))
    } else if v.fract() == 0.0 {
        format!("{v:.0}")
    } else if v.abs() >= 1.0 {
        let s = format!("{v:.1}");
        s.trim_end_matches('0').trim_end_matches('.').to_owned()
    } else {
        let s = format!("{v:.3}");
        s.trim_end_matches('0').trim_end_matches('.').to_owned()
    }
}

/// One series of a time chart: name, CSS color, one value per x.
struct Series<'a> {
    name: &'a str,
    color: &'a str,
    values: Vec<f64>,
}

#[derive(Clone, Copy, PartialEq)]
enum Mark {
    Step,
    Bars,
}

/// A chart over time (`xs` = bucket starts in seconds, width `dt`): stepped lines or grouped
/// bars, a linear or log y axis, a hover column per bucket with every series' readout.
fn time_chart(
    title: &str,
    y_unit: &str,
    xs: &[f64],
    dt: f64,
    series: &[Series<'_>],
    log: bool,
    mark: Mark,
) -> String {
    let mut o = format!("<div class=\"chart\"><h3>{}</h3>", esc(title));
    if series.len() > 1 {
        o += "<div class=\"legend\">";
        for s in series {
            let _ = write!(
                o,
                "<span><i style=\"background:{}\"></i>{}</span>",
                s.color,
                esc(s.name)
            );
        }
        o += "</div>";
    }
    let x_end = xs.last().map(|x| x + dt).unwrap_or(1.0).max(dt);
    let pw = CW - ML - MR;
    let ph = CH - MT - MB;
    let px = |x: f64| ML + x / x_end * pw;
    let all: Vec<f64> = series
        .iter()
        .flat_map(|s| s.values.iter().copied())
        .filter(|v| v.is_finite())
        .collect();
    let max = all.iter().copied().fold(0.0, f64::max);
    let (ticks, py): (Vec<f64>, Box<dyn Fn(f64) -> f64>) = if log {
        let lo = all
            .iter()
            .copied()
            .filter(|v| *v > 0.0)
            .fold(f64::INFINITY, f64::min);
        let lo = if lo.is_finite() { lo } else { 0.1 };
        let (a, b, t) = log_ticks(lo, max.max(lo));
        let (la, lb) = (a.log10(), b.log10());
        (
            t,
            Box::new(move |v: f64| MT + ph - (v.max(a).log10() - la) / (lb - la) * ph),
        )
    } else {
        let (top, t) = lin_ticks(max);
        (t, Box::new(move |v: f64| MT + ph - v.max(0.0) / top * ph))
    };
    let _ = write!(
        o,
        "<svg class=\"viz\" viewBox=\"0 0 {CW} {CH}\" role=\"img\" aria-label=\"{}\">",
        esc(title)
    );
    for t in &ticks {
        let y = py(*t);
        let _ = write!(
            o,
            "<line class=\"gr\" x1=\"{ML}\" x2=\"{:.1}\" y1=\"{y:.1}\" y2=\"{y:.1}\"/><text x=\"{:.1}\" y=\"{:.1}\" text-anchor=\"end\">{}</text>",
            CW - MR,
            ML - 6.0,
            y + 3.5,
            esc(&tick_label(*t, y_unit))
        );
    }
    let (_, xt) = lin_ticks(x_end);
    for t in xt.iter().filter(|t| **t <= x_end + 1e-9) {
        let x = px(*t);
        let _ = write!(
            o,
            "<line class=\"ax\" x1=\"{x:.1}\" x2=\"{x:.1}\" y1=\"{:.1}\" y2=\"{:.1}\"/><text x=\"{x:.1}\" y=\"{:.1}\" text-anchor=\"middle\">{}s</text>",
            MT + ph,
            MT + ph + 4.0,
            MT + ph + 16.0,
            trim_num(*t)
        );
    }
    let _ = write!(
        o,
        "<line class=\"ax\" x1=\"{ML}\" x2=\"{:.1}\" y1=\"{:.1}\" y2=\"{:.1}\"/><text x=\"{:.1}\" y=\"{:.1}\" text-anchor=\"middle\">seconds since the measurement window started</text>",
        CW - MR,
        MT + ph,
        MT + ph,
        ML + pw / 2.0,
        CH - 2.0
    );
    match mark {
        Mark::Step => {
            for s in series {
                let mut d = String::new();
                let mut pen = false;
                for (i, v) in s.values.iter().enumerate() {
                    let ok = v.is_finite() && (!log || *v > 0.0);
                    if !ok {
                        pen = false;
                        continue;
                    }
                    let (x0, x1, y) = (px(xs[i]), px(xs[i] + dt), py(*v));
                    if pen {
                        let _ = write!(d, " V{y:.1} H{x1:.1}");
                    } else {
                        let _ = write!(d, " M{x0:.1},{y:.1} H{x1:.1}");
                        pen = true;
                    }
                }
                if !d.is_empty() {
                    let _ = write!(
                        o,
                        "<path class=\"ln\" stroke=\"{}\" d=\"{}\"/>",
                        s.color,
                        d.trim()
                    );
                }
            }
        }
        Mark::Bars => {
            let n = series.len().max(1) as f64;
            let slot = (pw * dt / x_end - 2.0).max(0.6);
            let bw = (slot / n).max(0.6);
            for (si, s) in series.iter().enumerate() {
                for (i, v) in s.values.iter().enumerate() {
                    if *v <= 0.0 || !v.is_finite() {
                        continue;
                    }
                    let x = px(xs[i]) + 1.0 + si as f64 * bw;
                    let y = py(*v);
                    let _ = write!(
                        o,
                        "<rect x=\"{x:.1}\" y=\"{y:.1}\" width=\"{:.1}\" height=\"{:.1}\" rx=\"1\" fill=\"{}\"/>",
                        (bw - if n > 1.0 { 1.0 } else { 0.0 }).max(0.6),
                        (MT + ph - y).max(0.5),
                        s.color
                    );
                }
            }
        }
    }
    // Hover columns with the readout of every series.
    for (i, x) in xs.iter().enumerate() {
        let (x0, x1) = (px(*x), px(x + dt));
        let mut tip = format!("{}–{} s", trim_num(*x), trim_num(x + dt));
        for s in series {
            if let Some(v) = s.values.get(i) {
                let shown = if y_unit == "ms" {
                    fmt_ms(*v)
                } else {
                    format!("{} {}", trim_num((v * 10.0).round() / 10.0), y_unit.trim())
                };
                let _ = write!(tip, " · {} {shown}", s.name);
            }
        }
        let xm = (x0 + x1) / 2.0;
        let _ = write!(
            o,
            "<g class=\"hit\"><rect x=\"{x0:.1}\" y=\"{MT}\" width=\"{:.1}\" height=\"{ph:.1}\"/><line class=\"xh\" x1=\"{xm:.1}\" x2=\"{xm:.1}\" y1=\"{MT}\" y2=\"{:.1}\"/><title>{}</title></g>",
            (x1 - x0).max(0.5),
            MT + ph,
            esc(&tip)
        );
    }
    o += "</svg></div>";
    o
}

fn timeline_section(r: &Report) -> String {
    let mut o = String::from("<section id=\"timeline\"><h2>Timeline</h2>");
    let tl = &r.timeline;
    if tl.is_empty() {
        o += "<p class=\"muted\">No per-second samples in this report.</p></section>\n";
        return o;
    }
    let xs: Vec<f64> = tl.iter().map(|p| p.t_s).collect();
    let dt = xs
        .windows(2)
        .map(|w| w[1] - w[0])
        .find(|d| *d > 0.0)
        .unwrap_or(1.0);
    // Timeline points are stamped at the start of their interval (like heatmap columns).
    let starts = xs;
    o += "<p class=\"sub\">One sample per second; hover a column for its values.</p>";
    o += &time_chart(
        "Throughput (operations per second)",
        "",
        &starts,
        dt,
        &[Series {
            name: "ops/s",
            color: "var(--s1)",
            values: tl.iter().map(|p| p.ops_per_s).collect(),
        }],
        false,
        Mark::Step,
    );
    o += &time_chart(
        "Operation latency (log scale)",
        "ms",
        &starts,
        dt,
        &[
            Series {
                name: "p50",
                color: "var(--s1)",
                values: tl.iter().map(|p| p.p50_ms).collect(),
            },
            Series {
                name: "p99",
                color: "var(--s2)",
                values: tl.iter().map(|p| p.p99_ms).collect(),
            },
        ],
        true,
        Mark::Step,
    );
    if tl.iter().any(|p| p.errors > 0 || p.throttled > 0) {
        o += &time_chart(
            "Errors and throttled operations per second",
            "",
            &starts,
            dt,
            &[
                Series {
                    name: "errors",
                    color: "var(--s8)",
                    values: tl.iter().map(|p| p.errors as f64).collect(),
                },
                Series {
                    name: "throttled",
                    color: "var(--s4)",
                    values: tl.iter().map(|p| p.throttled as f64).collect(),
                },
            ],
            false,
            Mark::Bars,
        );
    } else {
        o += "<p class=\"muted\">No errors or throttling during the window.</p>";
    }
    o += "</section>\n";
    o
}

fn heatmap_section(r: &Report) -> String {
    let h = &r.heatmap;
    let mut o = String::from("<section id=\"heatmap\"><h2>Latency heatmap</h2>");
    let max = h
        .counts
        .iter()
        .flat_map(|c| c.iter().copied())
        .max()
        .unwrap_or(0);
    if max == 0 || h.latency_buckets_ms.is_empty() {
        o += "<p class=\"muted\">No operation rows to draw.</p></section>\n";
        return o;
    }
    o += "<p class=\"sub\">Operations by start time (x) and latency (y, log buckets); darker = more \
          operations. Bands above the bulk are stragglers.</p>";
    let used: Vec<usize> = (0..h.latency_buckets_ms.len())
        .filter(|l| h.counts.iter().any(|c| c.get(*l).copied().unwrap_or(0) > 0))
        .collect();
    let (lo, hi) = (used[0], *used.last().unwrap_or(&used[0]));
    let rows = hi - lo + 1;
    let cols = h.counts.len().max(1);
    let ph = (rows as f64 * 18.0).clamp(90.0, 300.0);
    let height = MT + ph + MB;
    let pw = CW - ML - MR;
    let cw = pw / cols as f64;
    let rh = ph / rows as f64;
    let bound = |l: usize| -> String {
        h.latency_buckets_ms
            .get(l)
            .map(|b| tick_label(*b, "ms"))
            .unwrap_or_else(|| "∞".into())
    };
    let _ = write!(
        o,
        "<svg class=\"viz\" viewBox=\"0 0 {CW} {height:.0}\" role=\"img\" aria-label=\"Latency heatmap\">"
    );
    let label_every = (rows / 12).max(1);
    for (i, l) in (lo..=hi).enumerate() {
        let y = MT + ph - (i as f64 + 1.0) * rh;
        if i % label_every == 0 {
            let _ = write!(
                o,
                "<text x=\"{:.1}\" y=\"{:.1}\" text-anchor=\"end\">{}</text>",
                ML - 6.0,
                y + rh / 2.0 + 3.5,
                esc(&bound(l))
            );
        }
    }
    let lmax = (max as f64).ln().max(1e-9);
    for (t, col) in h.counts.iter().enumerate() {
        let t0 = h.t_buckets_s.get(t).copied().unwrap_or(t as f64);
        for l in lo..=hi {
            let c = col.get(l).copied().unwrap_or(0);
            if c == 0 {
                continue;
            }
            let step = if max <= 1 {
                4
            } else {
                1 + ((c as f64).ln() / lmax * 6.0).round() as usize
            };
            let x = ML + t as f64 * cw;
            let y = MT + ph - ((l - lo) as f64 + 1.0) * rh;
            let _ = write!(
                o,
                "<rect class=\"cell\" x=\"{x:.1}\" y=\"{y:.1}\" width=\"{:.1}\" height=\"{:.1}\" fill=\"var(--q{})\"><title>{}–{} s · {} – {} · {c} ops</title></rect>",
                (cw - 1.0).max(0.5),
                (rh - 1.0).max(0.5),
                step.clamp(1, 7),
                trim_num(t0),
                trim_num(t0 + h.bucket_width_s),
                esc(&bound(l)),
                esc(&bound(l + 1)),
            );
        }
    }
    let x_end = cols as f64 * h.bucket_width_s;
    let (_, xt) = lin_ticks(x_end);
    for t in xt.iter().filter(|t| **t <= x_end + 1e-9) {
        let x = ML + t / x_end.max(1e-9) * pw;
        let _ = write!(
            o,
            "<text x=\"{x:.1}\" y=\"{:.1}\" text-anchor=\"middle\">{}s</text>",
            MT + ph + 16.0,
            trim_num(*t)
        );
    }
    let _ = write!(
        o,
        "<line class=\"ax\" x1=\"{ML}\" x2=\"{:.1}\" y1=\"{:.1}\" y2=\"{:.1}\"/><text x=\"{:.1}\" y=\"{:.1}\" text-anchor=\"middle\">operation start (s) · latency bucket lower bound on the left</text></svg>",
        CW - MR,
        MT + ph,
        MT + ph,
        ML + pw / 2.0,
        height - 2.0
    );
    o += "<div class=\"legend\"><span>fewer</span>";
    for q in 1..=7 {
        let _ = write!(o, "<span><i style=\"background:var(--q{q})\"></i></span>");
    }
    let _ = write!(o, "<span>more (max {max} ops per cell)</span></div>");
    o += "</section>\n";
    o
}

